#!/usr/bin/env python3
"""Generate a current-file-inventory Mermaid overview for AI navigation.

Does not invent citation counts. Edge weights live in the JSON crossref indexes.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from corpus_paths import ADOPTED_IMPLEMENTATION_WRAPPERS, CORE_FILES


GROUPS = (
    ("Preamble and Chapter One (Constitutional Map)", ("core_00.", "core_01.")),
    ("Chapter Two values and principles", ("core_02",)),
    ("Chapter Three definition stack", ("core_03",)),
    ("Chapter Four Rights Floor", ("core_04",)),
    ("Chapters Five to Seven: charters, separation of duties, Independent Bodies", ("core_05", "core_06", "core_07")),
    (
        "Chapters Eight to Sixteen: certification and standing pipelines",
        ("core_08", "core_09", "core_10", "core_11", "core_12", "core_13", "core_14", "core_15", "core_16"),
    ),
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=".", help="Repository root.")
    parser.add_argument("--output", required=True, help="Output .mmd path.")
    return parser.parse_args()


def node_id(name: str) -> str:
    return "".join(ch if ch.isalnum() else "_" for ch in name)


def files_for_prefixes(prefixes: tuple[str, ...]) -> list[str]:
    return [name for name in CORE_FILES if name.startswith(prefixes)]


def render(root: Path) -> str:
    lines = [
        "%% Generated by tools/generate_dependency_map.py. Do not edit by hand.",
        "%% Citation edges: ai_corpus/indexes/crossref_matrix.json and section_crossref.json.",
        "graph TB",
        '  subgraph Core["Core constitutional files"]',
    ]
    for title, prefixes in GROUPS:
        gid = node_id(title)
        members = files_for_prefixes(prefixes)
        if not members:
            continue
        lines.append(f'    subgraph {gid}["{title}"]')
        for name in members:
            nid = node_id(name)
            lines.append(f'      {nid}["{name}"]')
        lines.append("    end")
    lines.append("  end")
    lines.append('  subgraph AdoptedImplementation["Adopted implementation texts"]')
    for wrapper in ADOPTED_IMPLEMENTATION_WRAPPERS:
        nid = node_id(wrapper)
        folder = wrapper.replace(".md", "/")
        lines.append(f'    {nid}["{wrapper} + {folder}"]')
    lines.append("  end")
    lines.append("  Core --> AdoptedImplementation")
    return "\n".join(lines) + "\n"


def main() -> int:
    args = parse_args()
    root = Path(args.root).resolve()
    output = root / args.output
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(render(root), encoding="utf-8")
    print(f"Wrote dependency map to {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
