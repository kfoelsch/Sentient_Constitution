#!/usr/bin/env python3
"""Move the corpus edition label to a date (default: today).

Until the public announcement the edition is the current date: the label is
``SC-Corpus-YYYY.MM.DD`` and the effective date is the same day. Run this
when the text changes on a new day (``make edition-bump`` also regenerates the
files that embed the edition). The README edition table is the source of truth;
this tool reads the old edition and effective date from it and rewrites every
live pin to the new one.

What it changes: the old edition string wherever it appears, and the old
effective date on any line that says "effective" (``(effective 2026-08-09)``,
``"edition_effective": "..."``, ``| **Effective date** | ... |``). Other dates on
the same line are left alone.

What it leaves alone, because the pin there is a historical record:
  - archive/, evidence/, translations/ (pinned to the text they were made from),
    _pages_site/, ai_corpus/ and doc_architecture/generated/ (regenerated by
    tooling), docs/corpus_index.md (generated), .git/
  - evaluation/external_audit_*/ and dated result files under evaluation/**/results/
    (``YYYY-MM-DD_*.md`` record the edition they evaluated)
  - any line containing ``edition-pin: keep`` (an HTML comment marks a deliberate
    historical pin inside a live file)

Usage:
  bump_edition.py --root .                    # dry run: list what would change
  bump_edition.py --root . --write            # apply, bumping to today
  bump_edition.py --root . --write --date 2026-11-02
"""

from __future__ import annotations

import argparse
import re
import sys
from datetime import date, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EDITION_TZ = "America/Chicago"
KEEP_MARKER = "edition-pin: keep"
TEXT_SUFFIXES = {".md", ".json", ".txt", ".yml", ".yaml", ".py"}
SKIP_PREFIXES = (
    ".git/",
    "archive/",
    "evidence/",
    "translations/",
    "_pages_site/",
    "ai_corpus/",
    "doc_architecture/generated/",
    "docs/corpus_index.md",
    "tools/__pycache__/",
    "tools/bump_edition.py",
    "tools/test_bump_edition.py",
)
SKIP_PATTERNS = (
    re.compile(r"^evaluation/external_audit_[^/]+/"),
    re.compile(r"^evaluation/.+/results/\d{4}-\d{2}-\d{2}[_-]"),
)
EDITION_RE = re.compile(r"SC-Corpus-\d{4}\.\d{2}\.\d{2}(?:\.\d+)?")
README_EDITION_RE = re.compile(r"\*\*Corpus edition\*\*\s*\|\s*`?(SC-Corpus-[\d.]+)`?")
README_EFFECTIVE_RE = re.compile(r"\*\*Effective date\*\*\s*\|\s*(\d{4}-\d{2}-\d{2})")


def today() -> date:
    try:
        from zoneinfo import ZoneInfo

        return datetime.now(ZoneInfo(EDITION_TZ)).date()
    except Exception:  # no tz database: fall back to the machine's local date
        return date.today()


def edition_for(day: date) -> str:
    return f"SC-Corpus-{day:%Y.%m.%d}"


def read_current(root: Path) -> tuple[str, str]:
    text = (root / "README.md").read_text(encoding="utf-8")
    edition = README_EDITION_RE.search(text)
    effective = README_EFFECTIVE_RE.search(text)
    if not edition or not effective:
        raise SystemExit("README.md is missing the Corpus edition or Effective date row.")
    return edition.group(1), effective.group(1)


def skipped(rel: str) -> bool:
    return rel.startswith(SKIP_PREFIXES) or any(p.search(rel) for p in SKIP_PATTERNS)


def candidate_files(root: Path) -> list[Path]:
    files = []
    for path in sorted(root.rglob("*")):
        if not path.is_file() or path.suffix not in TEXT_SUFFIXES:
            continue
        rel = path.relative_to(root).as_posix()
        if skipped(rel):
            continue
        files.append(path)
    # Makefile and other extension-less files do not carry pins today; add them here if that changes.
    return files


def rewrite_text(text: str, old_edition: str, old_effective: str, new_edition: str, new_effective: str) -> tuple[str, int]:
    changed = 0
    out = []
    for line in text.splitlines(keepends=True):
        new_line = line
        if KEEP_MARKER not in line:
            if old_edition in line:
                new_line = new_line.replace(old_edition, new_edition)
            if old_effective in new_line and re.search(r"effective", line, re.I):
                new_line = new_line.replace(old_effective, new_effective)
        if new_line != line:
            changed += 1
        out.append(new_line)
    return "".join(out), changed


def bump(root: Path, new_day: date, write: bool) -> list[tuple[str, int]]:
    old_edition, old_effective = read_current(root)
    new_edition, new_effective = edition_for(new_day), new_day.isoformat()
    if (old_edition, old_effective) == (new_edition, new_effective):
        return []
    results: list[tuple[str, int]] = []
    for path in candidate_files(root):
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        if old_edition not in text and old_effective not in text:
            continue
        new_text, changed = rewrite_text(text, old_edition, old_effective, new_edition, new_effective)
        if changed:
            results.append((path.relative_to(root).as_posix(), changed))
            if write:
                path.write_text(new_text, encoding="utf-8")
    return results


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--date", help="edition day, YYYY-MM-DD (default: today in %s)" % EDITION_TZ)
    parser.add_argument("--write", action="store_true", help="apply the change (default is a dry run)")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    root = args.root.resolve()
    new_day = date.fromisoformat(args.date) if args.date else today()
    old_edition, old_effective = read_current(root)
    new_edition = edition_for(new_day)
    if old_edition == new_edition and old_effective == new_day.isoformat():
        print(f"Edition is already {new_edition} (effective {old_effective}); nothing to do.")
        return 0
    results = bump(root, new_day, write=args.write)
    verb = "Changed" if args.write else "Would change"
    for rel, count in results:
        print(f"{verb} {rel}: {count} line(s)")
    total = sum(count for _, count in results)
    print(f"{verb} {total} line(s) in {len(results)} file(s): {old_edition} ({old_effective}) -> {new_edition} ({new_day.isoformat()})")
    if args.write:
        print("Next: `make edition-bump` also regenerates the files that embed the edition; or run `make ai-corpus-sync plain-terms-edition reader-accessibility print-pack pages-corpus-index`.")
    else:
        print("Dry run. Re-run with --write to apply.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
